    public Task<Guid?> CreateLegajoDocumentAsync(Document document, CancellationToken ct)
    {
        if (RaceWinnerOnInsert is { } winner)
            return Task.FromResult<Guid?>(winner);

        lock (_gate)
        {
            var existing = Documents.FirstOrDefault(d => d.PersonLegajoId == document.PersonLegajoId
                && d.FileHashSHA256 == document.FileHashSHA256 && !d.IsDeleted);
            if (existing is not null)
                return Task.FromResult<Guid?>(existing.DocumentId);

            Documents.Add(document);
            return Task.FromResult<Guid?>(null);
        }
    }

    /// <summary>Runs inside TryTransitionAsync before its conditions are read: another request "lands" here.</summary>
    public Action? BeforeTransition { get; set; }

