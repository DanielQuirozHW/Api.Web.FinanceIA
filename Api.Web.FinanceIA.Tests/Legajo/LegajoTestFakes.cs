    private int _createCalls;
    private readonly object _gate = new();

    /// <summary>The repository's rule over the in-memory list (company rows, window, ordinal-ignore-case).</summary>
    public Task<Document?> FindRecentByHashAsync(Guid entityId, string tenantId, string? fileHashSha256, string documentType, DateTime uploadedSinceUtc, CancellationToken ct)
    {
        if (FindRecentThrows is not null)
            throw FindRecentThrows;

        if (string.IsNullOrWhiteSpace(fileHashSha256))
            return Task.FromResult<Document?>(null);

        lock (_gate)
        {
            return Task.FromResult(documents
                .Where(d => d.TenantId == tenantId
                         && d.EntityId == entityId
                         && !d.IsDeleted
                         && d.PersonLegajoId == null
                         && !string.IsNullOrWhiteSpace(d.FileHashSHA256)
                         && string.Equals(d.FileHashSHA256, fileHashSha256, StringComparison.OrdinalIgnoreCase)
                         && string.Equals(d.DocumentType, documentType, StringComparison.OrdinalIgnoreCase)
                         && d.UploadedAt >= uploadedSinceUtc)
                .OrderByDescending(d => d.UploadedAt)
                .FirstOrDefault());
        }
    }

    public Task<string?> GetLatestExtractionErrorByHashAsync(string? fileHashSha256, string tenantId, CancellationToken ct)
        => Task.FromResult<string?>(null);

    public Task<int> SumExtractionAttemptsByHashAsync(string? fileHashSha256, string tenantId, CancellationToken ct)
