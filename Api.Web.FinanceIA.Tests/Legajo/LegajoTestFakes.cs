            .OrderBy(c => c.CorrectedAt)
            .ToList());

    /// <summary>Runs inside InsertCorrectionAndReopenAsync before its writes: another request "lands" here.</summary>
    public Action? BeforeCorrectionCommit { get; set; }

    /// <summary>Runs inside TryApproveExtractionAsync before its conditions are read.</summary>
    public Action? BeforeApprove { get; set; }

    public Task<bool> InsertCorrectionAndReopenAsync(
        LegajoCorrection correction, Guid documentId, string tenantId, DateTime now, CancellationToken ct)
    {
        BeforeCorrectionCommit?.Invoke();

        lock (_gate)
        {
            Corrections.Add(correction);

            var d = Documents.SingleOrDefault(x => x.DocumentId == documentId && x.TenantId == tenantId
                                                && x.LegajoStatus == LegajoStatuses.Ready && !x.IsDeleted);
            if (d is null)
                return Task.FromResult(false);

            d.LegajoStatus = LegajoStatuses.NeedsReview;
            d.LegajoStatusUpdatedAt = now;
            Transitions.Add((documentId, LegajoStatuses.Ready, LegajoStatuses.NeedsReview));

            var run = Runs.SingleOrDefault(r => r.ExtractionId == correction.ExtractionId && r.TenantId == tenantId);
            if (run is not null)
            {
                run.ReviewedBy     = null;
                run.ReviewedAt     = null;
                run.ReviewOverride = null;
                run.ReviewReason   = null;
            }

            return Task.FromResult(true);
        }
    }

    public Task<bool> TryApproveExtractionAsync(
        Guid documentId, string tenantId, Guid extractionId, int expectedCorrections, Guid reviewedBy,
        bool isOverride, string? reason, DateTime now, CancellationToken ct)
    {
        BeforeApprove?.Invoke();

        lock (_gate)
        {
            var d = Documents.SingleOrDefault(x => x.DocumentId == documentId && x.TenantId == tenantId
                                                && x.LegajoStatus == LegajoStatuses.NeedsReview && !x.IsDeleted);
            var run = CurrentExtractions(tenantId).LastOrDefault(r => r.DocumentId == documentId);
            var count = Corrections.Count(c => c.ExtractionId == extractionId && c.TenantId == tenantId);

            if (d is null || run?.ExtractionId != extractionId || count != expectedCorrections)
                return Task.FromResult(false);

            d.LegajoStatus = LegajoStatuses.Ready;
            d.LegajoStatusUpdatedAt = now;
            Transitions.Add((documentId, LegajoStatuses.NeedsReview, LegajoStatuses.Ready));
            run.ReviewedBy     = reviewedBy;
            run.ReviewedAt     = now;
            run.ReviewOverride = isOverride;
            run.ReviewReason   = reason;
            return Task.FromResult(true);
        }
    }

}

/// <summary>
/// An <see cref="ILegajoReconciliationService"/> that records every trigger (legajo, tenant, trigger name) and
/// can be told to throw — the triggers must never let it fail their flow.
/// </summary>
internal sealed class RecordingReconciliationService : ILegajoReconciliationService
{
    public List<(Guid PersonLegajoId, string TenantId, string Trigger)> Triggers { get; } = [];

    public List<(Guid PersonLegajoId, string TenantId)> Rebuilds { get; } = [];

    /// <summary>What RebuildAsync answers; a found legajo with an empty result by default.</summary>
    public Func<Guid, LegajoRebuildOutcome>? Outcome { get; set; }

    public Task<LegajoRebuildOutcome> RebuildAsync(Guid personLegajoId, string tenantId, CancellationToken ct)
    {
        Rebuilds.Add((personLegajoId, tenantId));
        return Task.FromResult(Outcome?.Invoke(personLegajoId) ?? new LegajoRebuildOutcome(
            new LegajoReconciliationResultResponse
            {
                PersonLegajoId = personLegajoId, ItemsCount = 0, IncomesCount = 0, ItemsAdded = 0, ItemsUpdated = 0,
                ItemsRemoved = 0, ConfirmationsLapsed = 0, DocumentsUsed = [], DocumentsSkipped = []
            }, LegajoFound: true, LostRace: false));
    }

    public Task TryRebuildAsync(Guid personLegajoId, string tenantId, string trigger, CancellationToken ct)
    {
        Triggers.Add((personLegajoId, tenantId, trigger));
        return Task.CompletedTask;
    }
}

/// <summary>An <see cref="ILegajoReconciliationRepository"/> whose every call throws: a rebuild that fails outright.</summary>
internal sealed class ThrowingReconciliationRepository : ILegajoReconciliationRepository
{
    public Task<IReadOnlyList<LegajoItem>> GetItemsAsync(Guid personLegajoId, string tenantId, CancellationToken ct)
        => throw new InvalidOperationException("reconciliation store unavailable");

    public Task<IReadOnlyList<LegajoIncome>> GetIncomesAsync(Guid personLegajoId, string tenantId, CancellationToken ct)
        => throw new InvalidOperationException("reconciliation store unavailable");

    public Task<LegajoItem?> GetItemAsync(Guid itemId, Guid personLegajoId, string tenantId, CancellationToken ct)
        => throw new InvalidOperationException("reconciliation store unavailable");

