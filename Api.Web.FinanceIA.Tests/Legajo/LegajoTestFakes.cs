    public Action? BeforeConfirm { get; set; }

    public Task<bool> TryTransitionAsync(Guid documentId, string tenantId, string fromStatus, string toStatus, DateTime now, CancellationToken ct)
    {
        BeforeTransition?.Invoke();

        lock (_gate)
        {
            var d = Documents.SingleOrDefault(x => x.DocumentId == documentId && x.TenantId == tenantId
                                                && x.LegajoStatus == fromStatus && !x.IsDeleted);
            if (d is null)
                return Task.FromResult(false);

            d.LegajoStatus = toStatus;
            d.LegajoStatusUpdatedAt = now;
            Transitions.Add((documentId, fromStatus, toStatus));
            return Task.FromResult(true);
        }
    }

    public Task<bool> CompleteClassificationAsync(Guid documentId, string tenantId, string toStatus, DateTime? periodEnd,
        string? engagementType, string? holderCuit, DateTime now, CancellationToken ct)
    {
        lock (_gate)
        {
            var d = Documents.SingleOrDefault(x => x.DocumentId == documentId && x.TenantId == tenantId
                                                && x.LegajoStatus == LegajoStatuses.Classifying && !x.IsDeleted);
            if (d is null)
                return Task.FromResult(false);

            d.LegajoStatus   = toStatus;
            d.PeriodEnd      = periodEnd;
            d.EngagementType = engagementType;
            d.HolderCuit     = holderCuit;
            Transitions.Add((documentId, LegajoStatuses.Classifying, toStatus));
            return Task.FromResult(true);
        }
    }

    public Task<bool> ConfirmClassificationAsync(Guid documentId, string tenantId, string documentType, DateTime? periodEnd,
        DateTime now, CancellationToken ct)
    {
        BeforeConfirm?.Invoke();

        lock (_gate)
        {
            var d = Documents.SingleOrDefault(x => x.DocumentId == documentId && x.TenantId == tenantId
                                                && x.LegajoStatus == LegajoStatuses.NeedsReview && !x.IsDeleted);
            if (d is null)
                return Task.FromResult(false);

            d.LegajoStatus = LegajoStatuses.ReadyForExtraction;
            d.DocumentType = documentType;
            d.PeriodEnd    = periodEnd ?? d.PeriodEnd;
            Transitions.Add((documentId, LegajoStatuses.NeedsReview, LegajoStatuses.ReadyForExtraction));
            return Task.FromResult(true);
        }
    }

    public Task<bool> FailAsync(Guid documentId, string tenantId, string fromStatus, string errorCode, bool countsAsAttempt,
        DateTime now, CancellationToken ct)
    {
        lock (_gate)
        {
            var d = Documents.SingleOrDefault(x => x.DocumentId == documentId && x.TenantId == tenantId
                                                && x.LegajoStatus == fromStatus && !x.IsDeleted);
            if (d is null)
                return Task.FromResult(false);

            d.LegajoStatus           = LegajoStatuses.Failed;
            d.LastExtractionError    = errorCode;
            d.LastExtractionFailedAt = now;
            if (countsAsAttempt)
                d.ExtractionAttempts++;
            Failures.Add((documentId, errorCode, countsAsAttempt));
            return Task.FromResult(true);
        }
    }

    public Task InsertRunAsync(LegajoExtraction run, CancellationToken ct)
    {
        if (InsertRunThrows is not null)
            throw InsertRunThrows;

        lock (_gate)
        {
            if (run.IsCurrent)
            {
                foreach (var old in Runs.Where(r => r.DocumentId == run.DocumentId && r.Kind == run.Kind && r.IsCurrent))
                    old.IsCurrent = false;
            }

            Runs.Add(run);
        }

        return Task.CompletedTask;
    }

    public Task<bool> SetConsentAsync(Guid personLegajoId, string tenantId, Guid consentDocumentId, Guid recordedBy, DateTime now, CancellationToken ct)
    {
        var l = Legajos.SingleOrDefault(x => x.PersonLegajoId == personLegajoId && x.TenantId == tenantId);
        if (l is null) return Task.FromResult(false);
        l.ConsentRecordedAt = now;
        l.ConsentDocumentId = consentDocumentId;
        l.ConsentRecordedBy = recordedBy;
        return Task.FromResult(true);
    }

    public Task<bool> ClearConsentAsync(Guid personLegajoId, string tenantId, DateTime now, CancellationToken ct)
    {
        var l = Legajos.SingleOrDefault(x => x.PersonLegajoId == personLegajoId && x.TenantId == tenantId);
        if (l is null) return Task.FromResult(false);
        l.ConsentRecordedAt = null;
        l.ConsentDocumentId = null;
        l.ConsentRecordedBy = null;
        return Task.FromResult(true);
    }

    public Task<IReadOnlyList<(Guid DocumentId, string TenantId, string LegajoStatus)>> GetRecoverableAsync(
        DateTime staleCutoff, DateTime? waitingCutoff, IReadOnlyCollection<string> extractableTypes, CancellationToken ct)
        => Task.FromResult<IReadOnlyList<(Guid, string, string)>>(Documents
            .Where(d => d.PersonLegajoId != null && !d.IsDeleted
