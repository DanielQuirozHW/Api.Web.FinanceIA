internal sealed class InMemoryStorage : IDocumentStorageService
{
    public Dictionary<string, byte[]> Files { get; } = [];
    public Exception? ReadThrows { get; set; }

    /// <summary>Calls to SaveAsync (thread-safe count).</summary>
    public int SaveCalls => _saveCalls;

    /// <summary>When set, SaveAsync awaits it first — a slow blob write, for the concurrency tests.</summary>
    public Func<Task>? BeforeSave { get; set; }

    private int _saveCalls;

    public async Task<string> SaveAsync(string tenantId, Guid documentId, Stream content, CancellationToken ct)
    {
        Interlocked.Increment(ref _saveCalls);
        if (BeforeSave is not null)
            await BeforeSave().ConfigureAwait(false);

        return Save(tenantId, documentId, content);
    }

    private string Save(string tenantId, Guid documentId, Stream content)
    {
        using var buffer = new MemoryStream();
        content.CopyTo(buffer);
        var path = $"{tenantId}/{documentId}.pdf";
        lock (Files)
        {
            Files[path] = buffer.ToArray();
        }

        return path;
    }

    public Task<byte[]> ReadAsync(string storagePath, CancellationToken ct)
    {
        if (ReadThrows is not null)
            throw ReadThrows;
        return Task.FromResult(Files[storagePath]);
    }
}

