                          && (waitingCutoff == null || d.LegajoStatusUpdatedAt == null || d.LegajoStatusUpdatedAt < waitingCutoff))
                      || ((d.LegajoStatus == LegajoStatuses.Classifying || d.LegajoStatus == LegajoStatuses.Extracting)
                          && (d.LegajoStatusUpdatedAt == null || d.LegajoStatusUpdatedAt < staleCutoff))
                      || (d.LegajoStatus == LegajoStatuses.ReadyForExtraction
                          && extractableTypes.Contains(d.DocumentType)
                          && (waitingCutoff == null || d.LegajoStatusUpdatedAt == null || d.LegajoStatusUpdatedAt < waitingCutoff)
                          && Legajos.Any(l => l.PersonLegajoId == d.PersonLegajoId && l.TenantId == d.TenantId && IsActive(l)))))
            .Select(d => (d.DocumentId, d.TenantId, d.LegajoStatus!))
            .ToList());

