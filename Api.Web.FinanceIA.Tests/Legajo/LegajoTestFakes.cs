    public Task<IReadOnlyList<LegajoCorrection>> GetCorrectionsAsync(
        IReadOnlyCollection<Guid> extractionIds, string tenantId, CancellationToken ct)
        => Task.FromResult<IReadOnlyList<LegajoCorrection>>(Corrections
