/// <summary>Replays canned responses in order and records every request body. Counts hits.</summary>
internal sealed class ScriptedHandler(params (HttpStatusCode Status, string Body)[] responses) : HttpMessageHandler
{
    private int _next;

    public List<string> RequestBodies { get; } = [];

    public int Hits => RequestBodies.Count;

    /// <summary>The first this-many requests time out, as HttpClient.Timeout surfaces it.</summary>
    public int TimeoutsFirst { get; init; }

    protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken ct)
    {
        RequestBodies.Add(request.Content is null ? string.Empty : await request.Content.ReadAsStringAsync(ct));
        if (RequestBodies.Count <= TimeoutsFirst)
            throw new TaskCanceledException("timeout", new TimeoutException());
        var (status, body) = responses[Math.Min(_next++, responses.Length - 1)];
        return new HttpResponseMessage(status) { Content = new StringContent(body, Encoding.UTF8, "application/json") };
    }
}

