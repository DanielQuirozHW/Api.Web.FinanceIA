/// <summary>Builds synthetic PDFs with iText.</summary>
internal static class LegajoPdfFactory
{
    /// <summary>A native PDF: every page carries a real text layer.</summary>
    public static byte[] NativePdf(params string[] pageTexts)
    {
        using var buffer = new MemoryStream();
        using (var pdf = new PdfDocument(new PdfWriter(buffer)))
        using (var document = new LayoutDocument(pdf))
        {
            for (var i = 0; i < pageTexts.Length; i++)
            {
                if (i > 0)
                    document.Add(new AreaBreak(iText.Layout.Properties.AreaBreakType.NEXT_PAGE));
                document.Add(new Paragraph(pageTexts[i]));
            }
        }

        return buffer.ToArray();
    }

    /// <summary>A PDF whose pages have NO text layer (what a scan looks like to a text extractor).</summary>
    public static byte[] BlankPdf(int pages)
    {
        using var buffer = new MemoryStream();
        using (var pdf = new PdfDocument(new PdfWriter(buffer)))
        {
            for (var i = 0; i < pages; i++)
                pdf.AddNewPage();
        }

        return buffer.ToArray();
    }

    /// <summary>One empty page of <paramref name="widthPt"/> × <paramref name="heightPt"/> points.</summary>
    public static byte[] SizedPdf(float widthPt, float heightPt)
    {
        using var buffer = new MemoryStream();
        using (var pdf = new PdfDocument(new PdfWriter(buffer)))
        {
            pdf.AddNewPage(new iText.Kernel.Geom.PageSize(widthPt, heightPt));
        }

        return buffer.ToArray();
    }

    /// <summary>One text page followed by one empty page.</summary>
    public static byte[] MixedPdf(string text)
    {
        using var buffer = new MemoryStream();
        using (var pdf = new PdfDocument(new PdfWriter(buffer)))
        using (var document = new LayoutDocument(pdf))
        {
            document.Add(new Paragraph(text));
            document.Add(new AreaBreak(iText.Layout.Properties.AreaBreakType.NEXT_PAGE));
            // The second page stays empty: AreaBreak creates it, nothing is drawn on it.
        }

        return buffer.ToArray();
    }

