    public Task<bool> HasConsentAsync(Guid personLegajoId, string tenantId, CancellationToken ct)
    {
        HasConsentCalls++;
        if (ConsentOverride is not null)
            return Task.FromResult(ConsentOverride());

        return Task.FromResult(Legajos.Any(l => l.PersonLegajoId == personLegajoId && l.TenantId == tenantId
