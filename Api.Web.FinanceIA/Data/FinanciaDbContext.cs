using Api.Web.FinanceIA.Data.Configurations;
using Api.Web.FinanceIA.Data.Configurations.Financia;
using Api.Web.FinanceIA.Models.Entities;
using Api.Web.FinanceIA.Models.Financia;
using Microsoft.EntityFrameworkCore;

namespace Api.Web.FinanceIA.Data;

/// <summary>
/// EF Core DbContext for the per-tenant business database (financia-dev locally).
/// Maps only the tables needed for the current feature set.
/// Database First — never run migrations against this context.
/// Lazy loading and auto detect changes are disabled for performance.
/// </summary>
public sealed class FinanciaDbContext : DbContext
{
    /// <summary>
    /// Initializes the context with the provided options.
    /// Disables lazy loading and automatic change detection
    /// to reduce overhead on read-heavy workloads.
    /// </summary>
    public FinanciaDbContext(DbContextOptions<FinanciaDbContext> options)
        : base(options)
    {
        ChangeTracker.LazyLoadingEnabled = false;
        ChangeTracker.AutoDetectChangesEnabled = false;
    }

    /// <summary>
    /// Maps to [dbo].[Users].
    /// Contains user accounts per tenant.
    /// </summary>
    public DbSet<User> Users => Set<User>();

    /// <summary>
    /// Maps to [dbo].[MfaBackupCodes].
    /// Single-use MFA recovery codes, one row per code, keyed by the [dbo].[Users] row they
    /// belong to (FK_MfaBackupCodes_Users). Business data, which is why it lives here and not in
    /// the shared "Default" database beside the auth/config tables.
    /// </summary>
    public DbSet<MfaBackupCode> MfaBackupCodes => Set<MfaBackupCode>();

    /// <summary>
    /// Maps to [dbo].[AuditLogs].
    /// Append-only audit trail for security and compliance.
    /// </summary>
    public DbSet<AuditLog> AuditLogs => Set<AuditLog>();

    /// <summary>
    /// Maps to [dbo].[SessionLogs].
    /// Append-only session event log for security monitoring.
    /// </summary>
    public DbSet<SessionLog> SessionLogs => Set<SessionLog>();

    /// <summary>
    /// Maps to [dbo].[UserInvitations].
    /// Pending and consumed invitations sent by admins to onboard new users.
    /// </summary>
    public DbSet<UserInvitation> UserInvitations => Set<UserInvitation>();

    /// <summary>
    /// Maps to [dbo].[Entities].
    /// PyME records managed within a tenant.
    /// </summary>
    public DbSet<Entity> Entities => Set<Entity>();

    /// <summary>
    /// Maps to [dbo].[Documents].
    /// Financial documents uploaded for analysis.
    /// </summary>
    public DbSet<Document> Documents => Set<Document>();

    /// <summary>
    /// Maps to [dbo].[AnalysisResults].
    /// AI-generated output for each completed analysis.
    /// </summary>
    public DbSet<AnalysisResult> AnalysisResults => Set<AnalysisResult>();

    /// <summary>
    /// Minimal projection of [dbo].[Analyses] for join support.
    /// </summary>
    public DbSet<Analysis> Analyses => Set<Analysis>();

    /// <summary>
    /// Maps to [dbo].[ScoringConfig].
    /// Per-tenant configuration parameters for the deterministic credit-scoring engine.
    /// </summary>
    public DbSet<ScoringConfig> ScoringConfigs => Set<ScoringConfig>();

    /// <summary>
    /// Maps to [dbo].[AlertRuleCatalogue].
    /// Per-tenant catalogue of deterministic alert rules evaluated by the rule engine.
    /// </summary>
    public DbSet<AlertRuleDefinition> AlertRuleCatalogue => Set<AlertRuleDefinition>();

    /// <summary>
    /// Maps to [dbo].[ApiCallLogs].
    /// Append-only log of outbound API calls (Claude, BCRA, Dynamics, BYMA).
    /// </summary>
    public DbSet<ApiCallLog> ApiCallLogs => Set<ApiCallLog>();

    /// <summary>
    /// Maps to [dbo].[ExportLogs].
    /// Append-only audit log of every report exported from the system.
    /// </summary>
    public DbSet<ExportLog> ExportLogs => Set<ExportLog>();

    /// <summary>
    /// Maps to [dbo].[Alerts].
    /// Risk and informational alerts generated by the analysis engine.
    /// </summary>
    public DbSet<Alert> Alerts => Set<Alert>();

    /// <summary>Maps to [dbo].[ChatConversations]. Conversation headers linking to AnalysisResults.</summary>
    public DbSet<ChatConversation> ChatConversations => Set<ChatConversation>();

    /// <summary>Maps to [dbo].[ChatMessages]. Append-only chat turn storage.</summary>
    public DbSet<ChatMessage> ChatMessages => Set<ChatMessage>();

    /// <summary>Maps to [dbo].[Notes]. Append-only PyME-level internal analyst notes.</summary>
    public DbSet<Note> Notes => Set<Note>();

    /// <summary>Maps to [dbo].[CreditLines]. General credit line (cupo) per (Entity, Currency).</summary>
    public DbSet<CreditLine> CreditLines => Set<CreditLine>();

    /// <summary>Maps to [dbo].[CreditLineOperations]. Child operations under a credit line, tied to an approved analysis.</summary>
    public DbSet<CreditLineOperation> CreditLineOperations => Set<CreditLineOperation>();

    /// <summary>Maps to [dbo].[Fiadores]. Guarantors (fiadores) of a PyME, one row per (Entity, CUIT).</summary>
    public DbSet<Fiador> Fiadores => Set<Fiador>();

    /// <summary>
    /// Maps to [dbo].[PersonLegajos] (DDL 069). One legajo per persona humana per tenant, linked from
    /// [dbo].[Entities].PersonLegajoId. PII — never serialized wholesale into a Claude prompt.
    /// </summary>
    public DbSet<PersonLegajo> PersonLegajos => Set<PersonLegajo>();

    /// <summary>
    /// Maps to [dbo].[LegajoExtractions] (DDL 070). One immutable row per model run over a legajo
    /// document (classification now, extraction in Phase 2b); one current run per (document, kind).
    /// </summary>
    public DbSet<LegajoExtraction> LegajoExtractions => Set<LegajoExtraction>();

    /// <summary>
    /// Maps to [dbo].[LegajoCorrections] (DDL 070). Append-only analyst corrections to a run's fields.
    /// </summary>
    public DbSet<LegajoCorrection> LegajoCorrections => Set<LegajoCorrection>();

    /// <summary>
    /// Maps to [dbo].[LegajoItems] (DDL 071). The reconciled inventory of a legajo, rebuilt by
    /// LegajoReconciliationService; analyst edits survive a rebuild.
    /// </summary>
    public DbSet<LegajoItem> LegajoItems => Set<LegajoItem>();

    /// <summary>
    /// Maps to [dbo].[LegajoIncomes] (DDL 071). Incomes and sales of a legajo by period and source,
    /// replaced by every rebuild.
    /// </summary>
    public DbSet<LegajoIncome> LegajoIncomes => Set<LegajoIncome>();

    /// <summary>
    /// Maps to [dbo].[TenantSettings]. Per-tenant product-behaviour configuration as
    /// free-form key/value pairs (distinct from the numeric [dbo].[ScoringConfig]).
    /// </summary>
    public DbSet<TenantSettings> TenantSettings => Set<TenantSettings>();

    /// <summary>
    /// Maps to [dbo].[TenantBillingConfig]. Per-tenant billing/quota limits — one row per tenant.
    /// Nothing enforces these limits yet (billing v1, phase 1: config foundation only).
    /// </summary>
    public DbSet<TenantBillingConfig> TenantBillingConfigs => Set<TenantBillingConfig>();

    /// <summary>
    /// Maps to [dbo].[Notifications]. PER-USER delivery layer, distinct from the per-tenant
    /// [dbo].[Alerts]: each row is addressed to one UserId and carries its own read state.
    /// </summary>
    public DbSet<Notification> Notifications => Set<Notification>();

    /// <summary>
    /// Maps to [dbo].[UserApprovalLimits]. How much one user may commit directly, per currency,
    /// before an analysis needs a second signature. No row for a (user, currency) means that user
    /// cannot approve in it directly — only pre-approve.
    /// </summary>
    public DbSet<UserApprovalLimit> UserApprovalLimits => Set<UserApprovalLimit>();

    /// <summary>
    /// Maps to [dbo].[Teams]. Groups users within a tenant and names the manager an escalation from
    /// that team is routed to. A user with no team, or a team with no manager, falls back to the
    /// tenant's active RiskManagers.
    /// </summary>
    public DbSet<Team> Teams => Set<Team>();

    /// <summary>
    /// Maps to [dbo].[TeamManagers] (DDL 064). One row per manager of a team — a team may have
    /// several, and all of them are notified when an analyst of that team pre-approves. Composite
    /// key (TeamId, UserId). Teams.ManagerUserId is retained but deprecated; the notifier reads the
    /// union of the two.
    /// </summary>
    public DbSet<TeamManager> TeamManagers => Set<TeamManager>();

    /// <summary>
    /// Maps to [dbo].[AnalysisApprovalVotes] (DDL 067). One row per manager per analysis, recording
    /// how that manager voted on a pre-approval. Keyed on AnalysisId — NOT ResultId — because the
    /// decision state machine lives on [dbo].[Analyses]. The quorum engine counts the 'Approved' rows
    /// against the analyst's team's Teams.ApprovalQuorum.
    /// </summary>
    public DbSet<AnalysisApprovalVote> AnalysisApprovalVotes => Set<AnalysisApprovalVote>();

    /// <summary>
    /// Maps to [dbo].[AnalysisParticipants] (DDL 072). The role of each person in an analysis, with the
    /// persona humana evaluation frozen on the row. Written once by POST /api/person-analyses.
    /// </summary>
    public DbSet<AnalysisParticipant> AnalysisParticipants => Set<AnalysisParticipant>();

    /// <summary>
    /// Maps to [dbo].[AnalysisRescores] (DDL 073). One append-only row per re-score of a balance
    /// analysis: the score before and after, and the previous value of every overwritten column.
    /// </summary>
    public DbSet<AnalysisRescore> AnalysisRescores => Set<AnalysisRescore>();

    /// <summary>
    /// Maps to [dbo].[AnalysisEdits] (DDL 001; TenantId NVARCHAR(100) since DDL 081). One append-only row
    /// per balance figure an analyst corrected by hand.
    /// </summary>
    public DbSet<AnalysisEdit> AnalysisEdits => Set<AnalysisEdit>();

    /// <inheritdoc />
    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // Apply only Financia configurations to avoid cross-contamination
        // with AppDbContext configurations in the same assembly.
        modelBuilder.ApplyConfiguration(new UserConfiguration());
        modelBuilder.ApplyConfiguration(new MfaBackupCodeConfiguration());
        modelBuilder.ApplyConfiguration(new AuditLogConfiguration());
        modelBuilder.ApplyConfiguration(new SessionLogConfiguration());
        modelBuilder.ApplyConfiguration(new UserInvitationConfiguration());
        modelBuilder.ApplyConfiguration(new EntityConfiguration());
        modelBuilder.ApplyConfiguration(new DocumentConfiguration());
        modelBuilder.ApplyConfiguration(new AnalysisResultConfiguration());
        modelBuilder.ApplyConfiguration(new AnalysisConfiguration());
        modelBuilder.ApplyConfiguration(new ScoringConfigConfiguration());
        modelBuilder.ApplyConfiguration(new AlertRuleCatalogueConfiguration());
        modelBuilder.ApplyConfiguration(new ApiCallLogConfiguration());
        modelBuilder.ApplyConfiguration(new ExportLogConfiguration());
        modelBuilder.ApplyConfiguration(new AlertConfiguration());
        modelBuilder.ApplyConfiguration(new ChatConversationConfiguration());
        modelBuilder.ApplyConfiguration(new ChatMessageConfiguration());
        modelBuilder.ApplyConfiguration(new NoteConfiguration());
        modelBuilder.ApplyConfiguration(new CreditLineConfiguration());
        modelBuilder.ApplyConfiguration(new CreditLineOperationConfiguration());
        modelBuilder.ApplyConfiguration(new FiadorConfiguration());
        modelBuilder.ApplyConfiguration(new PersonLegajoConfiguration());
        modelBuilder.ApplyConfiguration(new LegajoExtractionConfiguration());
        modelBuilder.ApplyConfiguration(new LegajoCorrectionConfiguration());
        modelBuilder.ApplyConfiguration(new LegajoItemConfiguration());
        modelBuilder.ApplyConfiguration(new LegajoIncomeConfiguration());
        modelBuilder.ApplyConfiguration(new TenantSettingsConfiguration());
        modelBuilder.ApplyConfiguration(new TenantBillingConfigConfiguration());
        modelBuilder.ApplyConfiguration(new NotificationConfiguration());
        modelBuilder.ApplyConfiguration(new UserApprovalLimitConfiguration());
        modelBuilder.ApplyConfiguration(new TeamConfiguration());
        modelBuilder.ApplyConfiguration(new TeamManagerConfiguration());
        modelBuilder.ApplyConfiguration(new AnalysisApprovalVoteConfiguration());
        modelBuilder.ApplyConfiguration(new AnalysisParticipantConfiguration());
        modelBuilder.ApplyConfiguration(new AnalysisRescoreConfiguration());
        modelBuilder.ApplyConfiguration(new AnalysisEditConfiguration());

        // Lets a projection pull one scalar out of an nvarchar(max) JSON column without selecting
        // the blob — see AnalysisResultDetailProjection, which reads the two fields the Score needs
        // out of BcraDataJson rather than shipping all 40KB of it. EF Core 9 has no
        // EF.Functions.JsonValue, so the translation has to be declared here.
        //
        // Guarded because HasDbFunction is a relational-only concept: on the InMemory provider the
        // behavioural tests use, the mapping is absent and EF client-evaluates the C# body of
        // SqlJsonFunctions.JsonValue instead, which is written to agree with T-SQL.
        if (Database.IsRelational())
        {
            modelBuilder
                .HasDbFunction(typeof(SqlJsonFunctions)
                    .GetMethod(nameof(SqlJsonFunctions.JsonValue), [typeof(string), typeof(string)])!)
                .HasName("JSON_VALUE")
                .IsBuiltIn();
        }
    }
}
