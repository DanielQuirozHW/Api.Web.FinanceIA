using Api.Web.FinanceIA.Models.Financia;

namespace Api.Web.FinanceIA.Servicios;

/// <summary>
/// Folds <c>BcraChequesData.Detalle</c> into a continuous, month-indexed series: the bars
/// (<c>montoRechazado</c> per month) and the line (<c>saldoNeto</c>, the cumulative live debt) that
/// back the rejected-cheque chart.
///
/// <para>
/// A rule-for-rule port of the Portal's <c>buildChequesEvolucion</c>
/// (<c>apps/portal/src/lib/bcra-cheques-evolucion.ts</c>), which computed exactly this in the
/// browser from the full ~2936-row array. Moving the fold to this side is what let
/// GET /api/analyses/{id}/bcra/cheques stop shipping that array by default — the endpoint now sends
/// the ~24-point result instead. The TypeScript remains the SPEC; the two are pinned against each
/// other case by case in <c>BcraChequesEvolucionParityTests</c>, so a rule that changes in one repo
/// and not the other fails a test rather than quietly drawing a different chart.
/// </para>
///
/// <para>
/// ── Dates: no parsing, no timezone, deliberately ──────────────────────────────────────────
/// The TypeScript reads the YYYY and MM digits straight out of the wire string because feeding a
/// BCRA calendar day to <c>new Date()</c> and projecting it to America/Argentina/Buenos_Aires rolls
/// a first-of-month back into the previous month. Here the dates are already <c>DateTime</c>, and
/// <c>AnalysisController.BcraJsonOpts</c> registers no date converter, so the value read back from
/// the stored blob keeps the calendar reading BCRA reported. <c>.Year</c> and <c>.Month</c>
/// therefore reproduce exactly the digits the TypeScript reads lexically — and this file must never
/// acquire a <c>ToLocalTime</c>, <c>ToUniversalTime</c> or <c>TimeZoneInfo</c> call, which is the
/// only way that guarantee could be lost.
/// </para>
///
/// <para>
/// ── Field traps ───────────────────────────────────────────────────────────────────────────
/// · <c>FechaPagoMulta</c> / <c>EstadoMulta</c> concern the MULTA (the fine), NOT the cheque. The
///   cheque's settlement date is <c>FechaPago</c>. Neither is read here.
/// · <c>Pagado</c> is authoritative for WHETHER a cheque is settled; <c>FechaPago</c> is read only
///   for WHEN. <c>BcraService.MapCheques</c> derives the first from the second, so the two agree in
///   practice — but the rule is the TypeScript's, and re-deriving it here would diverge on the
///   hand-written rows where they disagree.
/// </para>
///
/// <para>
/// Pure, static and deterministic: no DI, no clock, no I/O. The result depends only on the rows,
/// never on when it was called — a frozen snapshot must not drift as it ages.
/// </para>
/// </summary>
public static class BcraChequesEvolucion
{
    /// <summary>
    /// A saldo below half a centavo is snapped to zero, so the line cannot sit a hair above the axis
    /// while a table formatting to 0 decimals prints "$ 0" beside it.
    ///
    /// <para>
    /// The TypeScript needs this to clear floating-point residue from summing montos — a fully
    /// recovered series would otherwise end at 1e-10 rather than 0. That specific hazard does NOT
    /// exist here: <c>decimal</c> sums these exactly, so an all-recovered series lands on 0 by
    /// arithmetic. The threshold is kept anyway, and is still live for a genuinely sub-centavo
    /// saldo, because dropping it would leave the two implementations differing on a rule rather
    /// than on a representation.
    /// </para>
    /// </summary>
    private const decimal CentavoEpsilon = 0.005m;

    /// <summary>
    /// Backstop against a corrupt pair of dates centuries apart allocating a huge list.
    /// 600 months = 50 years, far beyond BCRA's ~24-month window.
    /// </summary>
    private const int MaxMeses = 600;

    /// <summary>
    /// Folds the flat cheque list into a continuous monthly series.
    ///
    /// <para>
    /// Fault-isolated by design: a row that cannot be placed is dropped from the series and counted
    /// in <see cref="ChequesEvolucion.SinFechaRechazo"/> rather than throwing — one bad row must
    /// never blank the chart. Every branch below is a null check or arithmetic on a value type, so
    /// this method is total: it has no throwing path to guard.
    /// </para>
    ///
    /// <para>
    /// The fold is into keyed dictionaries and the output is generated by walking start→end, so the
    /// result is ascending and identical regardless of input order — which matters because the
    /// stored <c>detalle</c> arrives <c>fechaRechazo</c> DESCENDING.
    /// </para>
    ///
    /// <para>
    /// Invariant, verifiable by hand against the rendered table:
    /// <c>SaldoNeto[m] == Σ_{k&lt;=m} (MontoRechazado[k] − MontoRecuperado[k])</c> and
    /// <c>SaldoNeto[m] &gt;= 0</c>.
    /// </para>
    /// </summary>
    /// <param name="detalle">
    /// The stored per-cheque rows. Null is expected, not exceptional: the BFF documents
    /// <c>detalle</c> as null for legacy stored data, and frozen snapshots really do arrive without
    /// it.
    /// </param>
    /// <returns>The series plus its totals and axis maxima. Never null; all-zero for no usable rows.</returns>
    public static ChequesEvolucion Build(IReadOnlyList<BcraChequeDetalle>? detalle)
    {
        var rechazoCount    = new Dictionary<int, int>();
        var rechazoMonto    = new Dictionary<int, decimal>();
        var recuperadoMonto = new Dictionary<int, decimal>();

        var totalRecuperado = 0m;
        var sinFechaRechazo = new ChequesSinFecha();
        var sinFechaPago    = new ChequesSinFecha();

        int? primerRechazo = null;
        int? ultimoRechazo = null;
        int? ultimoPago    = null;

        foreach (var row in detalle ?? [])
        {
            if (row is null) continue;

            var monto = row.Monto;

            // `Pagado` decides WHETHER, always — never inferred from the presence of a date. Counted
            // BEFORE the date check, so a row the series cannot place still reaches the total.
            var settled = row.Pagado;
            if (settled) totalRecuperado += monto;

            if (row.FechaRechazo is not { } fechaRechazo)
            {
                // No rejection month → the row cannot be placed on a time axis at all. It still
                // counts toward totalRecuperado above, and is surfaced here so the caller can say
                // so rather than quietly dropping money off the chart.
                sinFechaRechazo.Cantidad += 1;
                sinFechaRechazo.Monto    += monto;
                continue;
            }

            var rechazoKey = MonthKey(fechaRechazo);

            AddTo(rechazoCount, rechazoKey, 1);
            AddTo(rechazoMonto, rechazoKey, monto);
            if (primerRechazo is null || rechazoKey < primerRechazo) primerRechazo = rechazoKey;
            if (ultimoRechazo is null || rechazoKey > ultimoRechazo) ultimoRechazo = rechazoKey;

            // FechaPago is read ONLY for WHEN, and only for a cheque already called settled. Two
            // irregular shapes normalise to the same rule — anchor the recovery at the rejection
            // month, so the cheque enters and leaves in the same month (net zero):
            //
            //   · no FechaPago (legacy/hand-written rows, since MapCheques derives Pagado from the
            //     date). Carrying it as live debt would contradict its own "Pagado" badge; dropping
            //     it from the line while leaving it in the bar would make the rendered table stop
            //     adding up (Rechazado $X · Recuperado $0 · Saldo neto $0). Anchoring keeps every
            //     column verifiable by hand, and the assumed timing is disclosed via SinFechaPago.
            //   · a payment dated BEFORE its rejection, which is simply corrupt. The alternative
            //     drags the series backwards into a meaningless negative live debt.
            if (settled)
            {
                int? pagoKey = row.FechaPago is { } fechaPago ? MonthKey(fechaPago) : null;
                if (pagoKey is null)
                {
                    sinFechaPago.Cantidad += 1;
                    sinFechaPago.Monto    += monto;
                }

                var effectivePago = pagoKey is null ? rechazoKey : Math.Max(pagoKey.Value, rechazoKey);
                AddTo(recuperadoMonto, effectivePago, monto);
                if (ultimoPago is null || effectivePago > ultimoPago) ultimoPago = effectivePago;
            }
        }

        if (primerRechazo is not { } start || ultimoRechazo is not { } lastRechazo)
        {
            return new ChequesEvolucion
            {
                Meses             = [],
                TotalRecuperado   = totalRecuperado,
                RecuperadoEnSerie = 0m,
                SinFechaRechazo   = sinFechaRechazo,
                SinFechaPago      = sinFechaPago,
                SaldoNetoFinal    = 0m,
                MaxMontoRechazado = 0m,
                MaxSaldoNeto      = 0m
            };
        }

        // The series ends at the last PAYMENT when that falls after the last rejection. Stopping at
        // the last rejection would freeze the line at its peak and hide a recovery that happened
        // afterwards — precisely the finding this chart exists for. It never extends to "today": a
        // frozen snapshot must not drift as it ages.
        var end = ultimoPago is { } lastPago && lastPago > lastRechazo ? lastPago : lastRechazo;

        var meses = new List<ChequeMesEvolucion>();
        var saldo = 0m;

        for (var mes = start; mes <= end && meses.Count < MaxMeses; mes = NextMonthKey(mes))
        {
            var montoRechazado  = rechazoMonto.GetValueOrDefault(mes);
            var montoRecuperado = recuperadoMonto.GetValueOrDefault(mes);

            saldo += montoRechazado - montoRecuperado;
            if (Math.Abs(saldo) < CentavoEpsilon) saldo = 0m;
            // Clamped, not merely snapped: every recovery is anchored at or after its own rejection
            // month, so a negative here would be arithmetically impossible.
            saldo = Math.Max(0m, saldo);

            meses.Add(new ChequeMesEvolucion
            {
                Mes                = mes,
                CantidadRechazados = rechazoCount.GetValueOrDefault(mes),
                MontoRechazado     = montoRechazado,
                MontoRecuperado    = montoRecuperado,
                SaldoNeto          = saldo
            });
        }

        var recuperadoEnSerie = 0m;
        var maxMontoRechazado = 0m;
        var maxSaldoNeto      = 0m;
        foreach (var mes in meses)
        {
            recuperadoEnSerie += mes.MontoRecuperado;
            if (mes.MontoRechazado > maxMontoRechazado) maxMontoRechazado = mes.MontoRechazado;
            if (mes.SaldoNeto      > maxSaldoNeto)      maxSaldoNeto      = mes.SaldoNeto;
        }

        return new ChequesEvolucion
        {
            Meses             = meses,
            TotalRecuperado   = totalRecuperado,
            RecuperadoEnSerie = recuperadoEnSerie,
            SinFechaRechazo   = sinFechaRechazo,
            SinFechaPago      = sinFechaPago,
            SaldoNetoFinal    = meses.Count > 0 ? meses[^1].SaldoNeto : 0m,
            MaxMontoRechazado = maxMontoRechazado,
            MaxSaldoNeto      = maxSaldoNeto
        };
    }

    /// <summary>
    /// The calendar month of a date as YYYYMM (2025-03-15 → 202503). Reads <c>.Year</c> and
    /// <c>.Month</c> as they stand — no formatting, no parsing, no timezone projection. See the
    /// class remarks for why that last point is load-bearing rather than incidental.
    /// </summary>
    private static int MonthKey(DateTime value) => value.Year * 100 + value.Month;

    /// <summary>202412 → 202501. Integer arithmetic; no date type, so no rollover surprises.</summary>
    private static int NextMonthKey(int mes)
    {
        var year  = mes / 100;
        var month = mes % 100;
        return month == 12 ? (year + 1) * 100 + 1 : mes + 1;
    }

    private static void AddTo(Dictionary<int, int> bucket, int key, int amount)
        => bucket[key] = bucket.GetValueOrDefault(key) + amount;

    private static void AddTo(Dictionary<int, decimal> bucket, int key, decimal amount)
        => bucket[key] = bucket.GetValueOrDefault(key) + amount;
}
