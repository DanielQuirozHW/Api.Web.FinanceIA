namespace Api.Web.FinanceIA.Models.Financia;

/// <summary>
/// Strongly-typed result returned by <see cref="Api.Web.FinanceIA.Servicios.IClaudeService"/>.
/// Contains all data extracted from the Claude API response, pre-serialized for DB storage.
/// </summary>
public sealed record ClaudeAnalysisResult(
    /// <summary>JSON-serialized ratios object for DB storage in RatiosJson column.</summary>
    string RatiosJson,
    /// <summary>JSON-serialized alerts array for DB storage in RiskAlerts column.</summary>
    string AlertsJson,
    /// <summary>JSON-serialized anomalies array for DB storage in Anomalies column.</summary>
    string AnomaliesJson,
    /// <summary>
    /// JSON-serialized balance check object (including fiscal_year_detected)
    /// for DB storage in BalanceJson column.
    /// </summary>
    string BalanceJson,
    /// <summary>Narrative executive summary from Claude.</summary>
    string ExecutiveSummary,
    /// <summary>Confidence score 0.0–1.0 as reported by Claude.</summary>
    decimal ConfidenceScore,
    /// <summary>Highest severity alert level found (critical > high > medium > low), or null.</summary>
    string? HighestAlertLevel,
    /// <summary>Whether the balance sheet is balanced per Claude's check.</summary>
    bool BalanceCheckBalanced,
    /// <summary>Percentage difference in balance check (assets - liabilities - equity).</summary>
    double BalanceDifferencePct,
    /// <summary>Number of input tokens consumed by the API call.</summary>
    int InputTokens,
    /// <summary>Number of output tokens generated by the API call.</summary>
    int OutputTokens,
    /// <summary>SHA-256 hex hash of the serialized request payload.</summary>
    string InputHash,
    /// <summary>SHA-256 hex hash of the raw API response text.</summary>
    string OutputHash
)
{
    /// <summary>Model ID that produced the kept extraction (e.g. "claude-sonnet-4-6").</summary>
    public string ModelUsed { get; init; } = string.Empty;

    /// <summary>
    /// The <c>output_config.effort</c> the extraction sent (Anthropic:ExtractionEffort, for a model
    /// that supports it), or null when none was sent. Not persisted; logs and the model-comparison
    /// harness read it.
    /// </summary>
    public string? EffortUsed { get; init; }

    /// <summary>
    /// Extraction method that produced the kept result:
    /// "document" (native PDF block, first pass), "image" (large file rendered to images, first
    /// pass), "image-fallback" (second pass of page images, no page needed turning) or
    /// "image-oriented" (second pass with at least one page turned upright — by its glyphs or, for a
    /// scan with no text layer, by the image detector). A wide page may also have gone as its two halves
    /// (integrity.extraction.splitPages). A second pass runs when the first is below the confidence
    /// threshold or fails a totals/structure integrity check.
    /// Not persisted as a column; recorded in BalanceJson.integrity.extraction.method.
    /// </summary>
    public string ExtractionMethod { get; init; } = string.Empty;

    /// <summary>Version tag of the extraction prompt that produced this result (e.g. "2.0").</summary>
    public string PromptVersion { get; init; } = string.Empty;

    /// <summary>
    /// Outcome of the deterministic balance integrity checks (BalanceJson.integrity.passed):
    /// false when a check failed, true when all that ran passed, null when the evaluation did not
    /// run or failed. Drives ValidationStatus alongside the model's own balance_check.
    /// </summary>
    public bool? BalanceIntegrityPassed { get; init; }

    /// <summary>
    /// The names of the integrity checks that failed (BalanceJson.integrity.checks[].name), in check order;
    /// null when the evaluation did not run or failed. Lets ValidationStatus tell a presentation-only failure
    /// (BalanceIntegrityService.FailsOnlyOnPresentation) apart; <see cref="BalanceIntegrityPassed"/> keeps the report's own verdict.
    /// </summary>
    public IReadOnlyList<string>? BalanceIntegrityFailedChecks { get; init; }

    /// <summary>
    /// Whether a failed net_profit_reconciliation is a sign flip (a misread net profit), from
    /// <c>BalanceIntegrityService.NetProfitSignFlipOf</c>; null when that check did not fail or nothing was evaluated.
    /// </summary>
    public bool? BalanceIntegrityNetProfitSignFlip { get; init; }

    /// <summary>
    /// Whether a failed net_profit_reconciliation is a column mix (pre-tax result and tax read from the comparative
    /// column), from <c>BalanceIntegrityService.NetProfitColumnMixOf</c>; null when that check did not fail or the mix
    /// could not be checked (no comparative net profit).
    /// </summary>
    public bool? BalanceIntegrityNetProfitColumnMix { get; init; }

    /// <summary>
    /// The scan-orientation call the second pass made, or null when none reached the API. Its tokens
    /// are NOT in <see cref="InputTokens"/>/<see cref="OutputTokens"/> (those are the extraction model's):
    /// the pipeline writes its own ApiCallLogs row, priced with its own model. Not persisted.
    /// </summary>
    public ScanOrientationUsage? OrientationDetection { get; init; }

    /// <summary>
    /// One entry per extraction pass that produced a usable answer (the first, and the second when it ran
    /// and answered), in pass order: the cap that answer was given and the tokens it produced. Read by the
    /// pipeline for the near-cap Warning (it knows the tenant; the service does not). Billing reads
    /// <see cref="InputTokens"/>/<see cref="OutputTokens"/>, not this. Not persisted.
    /// </summary>
    public IReadOnlyList<ExtractionPassUsage> ExtractionPasses { get; init; } = [];
}

/// <summary>
/// The output side of one extraction pass that answered: the model, the <c>max_tokens</c> the ANSWERING
/// call was sent with (the escalated cap when the pass escalated), the output tokens of that call alone,
/// and whether the pass escalated after a max_tokens stop.
/// </summary>
public sealed record ExtractionPassUsage(string Model, int MaxTokens, int OutputTokens, bool Escalated);
