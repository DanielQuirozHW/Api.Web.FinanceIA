using System.Text.Json.Serialization;

namespace Api.Web.FinanceIA.Models.Financia;

/// <summary>
/// Cash flow statement (Estado de Flujo de Efectivo) extracted from the balance document and
/// persisted inside the <c>BalanceJson</c> blob under the <c>cash_flow</c> key.
///
/// This is CONTEXT for the analyst, NOT a scoring input — it never feeds the risk score.
/// Figures are reported with the sign exactly as presented in the statement (outflows negative,
/// inflows positive). The only transformation is the unit scale (prompt 2.18+): a statement
/// "expresado en miles" is persisted in pesos via <see cref="Scale"/>, like the rest of BalanceJson.
///
/// When the document does not contain a cash flow statement, <see cref="Present"/> is false and
/// every other field is null. Older analyses predating this feature have no <c>cash_flow</c> key
/// at all — the read side distinguishes that (null model) from an explicit not-present snapshot.
/// </summary>
public sealed record CashFlowData
{
    [JsonPropertyName("present")]
    public bool Present { get; init; }

    [JsonPropertyName("method")]
    public string? Method { get; init; }

    [JsonPropertyName("cash_beginning")]
    public double? CashBeginning { get; init; }

    [JsonPropertyName("cash_end")]
    public double? CashEnd { get; init; }

    [JsonPropertyName("net_change")]
    public double? NetChange { get; init; }

    [JsonPropertyName("operating")]
    public double? Operating { get; init; }

    [JsonPropertyName("investing")]
    public double? Investing { get; init; }

    [JsonPropertyName("financing")]
    public double? Financing { get; init; }

    /// <summary>
    /// Signed amount of the monetary/inflation result generated by holding cash
    /// (RT6: RECPAM / resultado por exposición al poder adquisitivo sobre el efectivo). Populated
    /// whenever the statement discloses a distinct RECPAM-on-cash line — whether that line sits
    /// OUTSIDE the three activity subtotals as a reconciling item, or WITHIN one activity section's
    /// subtotal. <see cref="MonetaryResultOnCashSection"/> disambiguates the placement. Null when
    /// the statement presents no such line.
    /// </summary>
    [JsonPropertyName("monetary_result_on_cash")]
    public double? MonetaryResultOnCash { get; init; }

    /// <summary>
    /// Where the balance exposed the RECPAM-on-cash line, so the reconciliation knows whether the
    /// amount is a separate term or already folded into a section subtotal. One of
    /// <c>"operating"</c>, <c>"investing"</c>, <c>"financing"</c> (the line is inside that section's
    /// subtotal) or <c>"outside"</c> (a standalone reconciling line, disjoint from the three
    /// sections). Null when the statement discloses no such line, or for analyses predating
    /// extraction prompt 2.6 (which only ever emitted the amount for the "outside" case — the read
    /// side treats a null section as "outside" so historical verdicts stay identical).
    /// </summary>
    [JsonPropertyName("monetary_result_on_cash_section")]
    public string? MonetaryResultOnCashSection { get; init; }

    [JsonPropertyName("components")]
    public CashFlowComponents? Components { get; init; }

    /// <summary>Returns a copy with every amount — components included — multiplied by <paramref name="factor"/>.</summary>
    public CashFlowData Scale(double factor) => factor == 1d ? this : this with
    {
        CashBeginning        = CashBeginning        * factor,
        CashEnd              = CashEnd              * factor,
        NetChange            = NetChange            * factor,
        Operating            = Operating            * factor,
        Investing            = Investing            * factor,
        Financing            = Financing            * factor,
        MonetaryResultOnCash = MonetaryResultOnCash * factor,
        Components           = Components?.Scale(factor),
    };
}

/// <summary>
/// Detail lines within the cash flow statement. Each is populated only when explicitly stated in
/// the document and carries the sign as presented (cash leaving the company is negative — including
/// dividends_paid, long_term_debt_repaid, short_term_debt_repaid, capex and director_fees_paid).
/// </summary>
public sealed record CashFlowComponents
{
    [JsonPropertyName("dividends_paid")]
    public double? DividendsPaid { get; init; }

    [JsonPropertyName("long_term_debt_raised")]
    public double? LongTermDebtRaised { get; init; }

    [JsonPropertyName("long_term_debt_repaid")]
    public double? LongTermDebtRepaid { get; init; }

    [JsonPropertyName("short_term_debt_raised")]
    public double? ShortTermDebtRaised { get; init; }

    [JsonPropertyName("short_term_debt_repaid")]
    public double? ShortTermDebtRepaid { get; init; }

    [JsonPropertyName("capital_contributions")]
    public double? CapitalContributions { get; init; }

    [JsonPropertyName("capex")]
    public double? Capex { get; init; }

    [JsonPropertyName("asset_disposals")]
    public double? AssetDisposals { get; init; }

    /// <summary>
    /// Cash placed into or returning from FINANCIAL instruments (plazo fijo, FCI, títulos, acciones,
    /// cuentas comitentes). Takes any financial-placement line EXCEPT one whose wording states a
    /// direction of RETURN (venta, rescate, recupero, cobro) — that one goes to
    /// <see cref="FinancialPlacementsRedeemed"/> instead. Direction-neutral and TERM-NEUTRAL: carries
    /// the sign exactly as presented (negative when cash leaves, positive when it returns), and its
    /// investing-section placement says nothing about term — a plazo fijo is a current asset, unlike
    /// a fixed-asset purchase in the same section. Distinct from <see cref="Capex"/> and
    /// <see cref="AssetDisposals"/>, which cover bienes de uso only.
    /// </summary>
    [JsonPropertyName("financial_placements")]
    public double? FinancialPlacements { get; init; }

    /// <summary>
    /// Cash returning from financial instruments on redemption or sale — populated ONLY when the
    /// statement line's own wording states that direction (venta, rescate, recupero, cobro), never
    /// inferred from the sign. Positive. Sales/redemptions of financial instruments belong here and
    /// never in <see cref="AssetDisposals"/>, which is reserved for bienes de uso.
    /// </summary>
    [JsonPropertyName("financial_placements_redeemed")]
    public double? FinancialPlacementsRedeemed { get; init; }

    /// <summary>
    /// Honorarios al directorio actually paid, as reported in the financing section. Negative when it
    /// represents cash leaving the company. A distribution to owners/administrators and a sibling of
    /// <see cref="DividendsPaid"/> — never merge the two, never fold either into the other.
    /// </summary>
    [JsonPropertyName("director_fees_paid")]
    public double? DirectorFeesPaid { get; init; }

    /// <summary>Returns a copy with every amount multiplied by <paramref name="factor"/>.</summary>
    public CashFlowComponents Scale(double factor) => factor == 1d ? this : this with
    {
        DividendsPaid               = DividendsPaid               * factor,
        LongTermDebtRaised          = LongTermDebtRaised          * factor,
        LongTermDebtRepaid          = LongTermDebtRepaid          * factor,
        ShortTermDebtRaised         = ShortTermDebtRaised         * factor,
        ShortTermDebtRepaid         = ShortTermDebtRepaid         * factor,
        CapitalContributions        = CapitalContributions        * factor,
        Capex                       = Capex                       * factor,
        AssetDisposals              = AssetDisposals              * factor,
        FinancialPlacements         = FinancialPlacements         * factor,
        FinancialPlacementsRedeemed = FinancialPlacementsRedeemed * factor,
        DirectorFeesPaid            = DirectorFeesPaid            * factor,
    };
}
