namespace Api.Web.FinanceIA.Models.Financia;

/// <summary>
/// EF Core entity that maps to [dbo].[AnalysisResults].
/// Stores the AI-generated output for a completed analysis. One record per analysis.
/// </summary>
public sealed class AnalysisResult
{
    /// <summary>Primary key.</summary>
    public Guid ResultId { get; set; }

    /// <summary>Analysis this result belongs to. One-to-one relationship with Analyses.</summary>
    public Guid AnalysisId { get; set; }

    /// <summary>Tenant that owns this result. Firebase tenant slug (e.g. SgrOneClickSandboxFB2).</summary>
    public string TenantId { get; set; } = string.Empty;

    /// <summary>JSON blob of the balance sheet data extracted from the document.</summary>
    public string? BalanceJson { get; set; }

    /// <summary>JSON blob of the financial ratios computed from the balance sheet.</summary>
    public string? RatiosJson { get; set; }

    /// <summary>JSON blob of BCRA (Central Bank) data used in the analysis.</summary>
    public string? BcraDataJson { get; set; }

    /// <summary>JSON blob of macroeconomic indicators used in the analysis.</summary>
    public string? MacroDataJson { get; set; }

    /// <summary>Risk score suggested by the AI model (0–100 scale). Null until AI completes.</summary>
    public decimal? AiSuggestedScore { get; set; }

    /// <summary>Risk level label suggested by the AI (e.g., Low, Medium, High, Critical).</summary>
    public string? AiSuggestedLevel { get; set; }

    /// <summary>Executive summary of the financial statements, generated during extraction.</summary>
    public string? ExecutiveSummary { get; set; }

    /// <summary>Score justification narrative generated by <c>GenerateScoringNarrativeAsync</c>.</summary>
    public string? ScoringNarrative { get; set; }

    /// <summary>JSON array of risk alerts identified by the AI.</summary>
    public string? RiskAlerts { get; set; }

    /// <summary>
    /// JSON array of alerts produced by the deterministic rule engine from the per-tenant
    /// catalogue. Distinct from <see cref="RiskAlerts"/>, which stays the AI's own findings.
    /// Null for analyses persisted before the catalogue existed — deliberately not backfilled.
    /// </summary>
    public string? CatalogueAlerts { get; set; }

    /// <summary>JSON array of anomalies detected by the AI.</summary>
    public string? Anomalies { get; set; }

    /// <summary>SHA-256 hash of the AI prompt input for auditability.</summary>
    public string AiInputHash { get; set; } = string.Empty;

    /// <summary>SHA-256 hash of the raw AI response for auditability.</summary>
    public string AiOutputHash { get; set; } = string.Empty;

    /// <summary>Number of tokens consumed by the AI prompt input.</summary>
    public int? AiInputTokens { get; set; }

    /// <summary>Number of tokens generated by the AI response.</summary>
    public int? AiOutputTokens { get; set; }

    /// <summary>Validation status of the result (e.g., Pending, Valid, Invalid).</summary>
    public string ValidationStatus { get; set; } = string.Empty;

    /// <summary>Optional notes from the reviewer explaining the validation decision.</summary>
    public string? ValidationNotes { get; set; }

    /// <summary>
    /// Whether the external-source (BCRA) enrichment behind this result actually happened:
    /// <c>Complete</c> | <c>NotApplicable</c> | <c>Degraded</c> — see
    /// <see cref="BcraEnrichmentOutcome"/>. Distinct from <see cref="ValidationStatus"/>, which is
    /// the balance-sheet arithmetic check and says nothing about data provenance.
    /// <para>
    /// A <c>Degraded</c> row scored WITHOUT the BCRA component: its weight was renormalised onto
    /// ratios and macro, which makes the score strictly worse. Before this column existed such a
    /// row was indistinguishable from a fully-enriched one. <c>NotApplicable</c> carries the same
    /// numeric penalty but permanently — there is no CUIT, so no retry can change it. Added by DDL
    /// 039; rows predating it backfill to <c>Complete</c> via a default constraint, so the value is
    /// only trustworthy for analyses created after 039.
    /// </para>
    /// </summary>
    public string EnrichmentStatus { get; set; } = string.Empty;

    /// <summary>
    /// Short es-AR diagnostic explaining a <c>Degraded</c> enrichment, for an analyst to read.
    /// Null for <c>Complete</c> and <c>NotApplicable</c>. Added by DDL 039.
    /// </summary>
    public string? EnrichmentNotes { get; set; }

    /// <summary>
    /// JSON blob of the per-ratio and per-component score breakdown produced by the
    /// deterministic scoring engine (see ScoringResult.Breakdown).
    /// </summary>
    public string? ScoreBreakdownJson { get; set; }

    /// <summary>
    /// JSON blob of the LUFE (government registry) data as it was when this analysis ran.
    /// Point-in-time snapshot copied from the entity at run time so the analysis view keeps
    /// showing the data used at calification time, independent of later entity refreshes.
    /// Null when the entity was unavailable or had no LUFE snapshot.
    /// </summary>
    public string? LufeDataJson { get; set; }

    /// <summary>
    /// JSON blob of the Fiscal/ARCA data as it was when this analysis ran.
    /// Point-in-time snapshot copied from the entity at run time so the analysis view keeps
    /// showing the data used at calification time, independent of later entity refreshes.
    /// Null when the entity was unavailable or had no Fiscal snapshot.
    /// </summary>
    public string? FiscalDataJson { get; set; }

    /// <summary>
    /// JSON blob of NOSIS data captured at analysis run time. Reserved for the future NOSIS
    /// integration; always null today (no integration produces this data yet).
    /// </summary>
    public string? NosisDataJson { get; set; }

    /// <summary>
    /// JSON blob of CASFOG data captured at analysis run time: a write-once copy of the entity's
    /// <c>CasfogDataJson</c>, never re-synced from the live entity afterwards. Null when the entity had
    /// no CASFOG snapshot — which is every entity of a tenant whose profile disables CASFOG. Since §7.4
    /// this is also the evidence behind the guarantee-arrears penalty: the engine scored the same bytes
    /// frozen here, which is what keeps a stored analysis reproducible.
    /// </summary>
    public string? CasfogDataJson { get; set; }

    /// <summary>UTC timestamp when this result was generated.</summary>
    public DateTime GeneratedAt { get; set; }

    /// <summary>
    /// UTC instant of the latest re-score (DDL 073), or null when the result was never re-scored.
    /// <see cref="GeneratedAt"/> keeps the original generation time; the history of every re-score is
    /// in [dbo].[AnalysisRescores].
    /// </summary>
    public DateTime? RescoredAt { get; set; }

    /// <summary>The user (Users.UserId) who ran the latest re-score; null when never re-scored.</summary>
    public Guid? RescoredBy { get; set; }

    /// <summary>
    /// How many times this result was re-scored (DDL 073, NOT NULL DEFAULT 0). Also the optimistic
    /// concurrency token of a re-score: the write is <c>UPDATE … WHERE ResultId = @id AND
    /// RescoreCount = @expected</c>, so two concurrent re-scores cannot both land.
    /// </summary>
    public int RescoreCount { get; set; }
}
